// Modal elements
const modal = document.getElementById("projectModal");
const modalOverlay = document.getElementById("modalOverlay");
const modalClose = document.getElementById("modalClose");
const modalTitle = document.getElementById("modalTitle");
const modalMeta = document.getElementById("modalMeta");
const modalDescription = document.getElementById("modalDescription");
const videosSection = document.getElementById("videosSection");
const videosGrid = document.getElementById("videosGrid");
const imagesSection = document.getElementById("imagesSection");
const imagesGrid = document.getElementById("imagesGrid");

// Open modal with project data
function openProjectModal(projectId) {
  const project = projectData[projectId];
  if (!project) return;

  // Set title and meta
  modalTitle.textContent = project.title;
  modalMeta.innerHTML = `
    <span class="sg-modal-meta-item"><strong>Location:</strong> ${project.location}</span>
    <span class="sg-modal-meta-item"><strong>Status:</strong> ${project.status}</span>
    <span class="sg-modal-meta-item"><strong>Capacity:</strong> ${project.capacity}</span>
  `;
  modalDescription.textContent = project.description;

  // Clear previous content
  videosGrid.innerHTML = "";
  imagesGrid.innerHTML = "";

  // Add videos (local files from videos folder) - standard video player, no thumbnail
  if (project.videos && project.videos.length > 0) {
    videosSection.style.display = "block";
    project.videos.forEach((video) => {
      const videoCard = document.createElement("div");
      videoCard.className = "sg-media-card sg-media-card--video";
      videoCard.innerHTML = `
        <h4>${video.title}</h4>
        <div class="sg-media-embed">
          <video src="${video.src}" controls playsinline></video>
        </div>
      `;
      videosGrid.appendChild(videoCard);
    });
  } else {
    videosSection.style.display = "none";
  }

  // Add images (local paths - hide card if image fails to load, so no blank placeholders)
  if (project.images && project.images.length > 0) {
    imagesSection.style.display = "block";
    project.images.forEach((image) => {
      const imageSrc = image.src || image.url;
      const imageCard = document.createElement("div");
      imageCard.className = "sg-media-card sg-media-card--image";
      const img = document.createElement("img");
      img.src = imageSrc;
      img.alt = image.alt || image.title;
      img.onerror = function () {
        if (this.parentElement) this.parentElement.style.display = "none";
      };
      imageCard.appendChild(img);
      imageCard.addEventListener("click", () => {
        if (imageSrc) window.open(imageSrc, "_blank");
      });
      imagesGrid.appendChild(imageCard);
    });
  } else {
    imagesSection.style.display = "none";
  }

  // Show modal
  modal.classList.add("sg-modal--open");
  document.body.style.overflow = "hidden";
}

// Close modal
function closeProjectModal() {
  modal.classList.remove("sg-modal--open");
  document.body.style.overflow = "";
}

// Event listeners
modalOverlay.addEventListener("click", closeProjectModal);
modalClose.addEventListener("click", closeProjectModal);

// Close on Escape key
document.addEventListener("keydown", (e) => {
  if (e.key === "Escape" && modal.classList.contains("sg-modal--open")) {
    closeProjectModal();
  }
});

// Add click handlers to project cards
document.querySelectorAll(".sg-project-card[data-project-id]").forEach((card) => {
  card.addEventListener("click", () => {
    const projectId = card.getAttribute("data-project-id");
    openProjectModal(projectId);
  });
});
